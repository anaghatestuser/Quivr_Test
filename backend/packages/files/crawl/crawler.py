    def process(self):
        # Extract and combine content recursively
        visited_urls = set()
        extracted_content = self._process_recursive(self.url, self.depth, visited_urls)

        # Create a file
        file_name = slugify(self.url) + ".txt"
        temp_file_path = os.path.join(tempfile.gettempdir(), file_name)
        with open(temp_file_path, "w") as temp_file:
            try:
                extracted_content = gr_check(extracted_content, "agent", "file", candidate_policies=['AI_DAT_SEC_025'], site_id='site:sha256:04c159eb7e4b2ef47c262131a815a59c0058a3c4fe36ed8b764b338e15304932')
            except Exception as _gr_exc:
                if type(_gr_exc).__name__ == "GRBlockedError": raise
                extracted_content = extracted_content
                __import__("logging").getLogger("lineaje.gr_client").warning("Lineaje guardrail unavailable at 'agent->file' — passing data through unchecked")
            temp_file.write(extracted_content)  # type: ignore

        return temp_file_path, file_name

    def checkGithub(self):
        return "github.com" in self.url


